// Load test for POST /api/v1/integrations/{integrationId}/alerts.
//
// Run with k6 (https://k6.io):
//   k6 run tests/load/alert-ingestion.js \
//     -e BASE_URL=https://api.example.com \
//     -e INTEGRATION_ID=<integration id> \
//     -e API_KEY=<plaintext API key, shown once at integration creation> \
//     -e SIGNING_SECRET=<plaintext signing secret, shown once at integration creation>
//
// Create a disposable integration for this (e.g. via a "Load Test" service) rather
// than reusing a production one, since every iteration writes a real Alert row.
import http from 'k6/http';
import crypto from 'k6/crypto';
import { check, sleep } from 'k6';

export const options = {
  scenarios: {
    steady_ingestion: {
      executor: 'ramping-vus',
      startVUs: 0,
      stages: [
        { duration: '30s', target: 20 },
        { duration: '2m', target: 20 },
        { duration: '30s', target: 0 },
      ],
    },
  },
  thresholds: {
    http_req_failed: ['rate<0.01'],
    http_req_duration: ['p(95)<500'],
  },
};

const BASE_URL = __ENV.BASE_URL || 'http://localhost:5000';
const INTEGRATION_ID = __ENV.INTEGRATION_ID;
const API_KEY = __ENV.API_KEY;
const SIGNING_SECRET = __ENV.SIGNING_SECRET;

if (!INTEGRATION_ID || !API_KEY || !SIGNING_SECRET) {
  throw new Error('INTEGRATION_ID, API_KEY, and SIGNING_SECRET env vars are required.');
}

function sign(timestamp, body) {
  return crypto.hmac('sha256', SIGNING_SECRET, `${timestamp}.${body}`, 'hex');
}

export default function () {
  const body = JSON.stringify({
    externalId: `load-${__VU}-${__ITER}-${Date.now()}`,
    source: 'k6-load-test',
    title: 'Synthetic load-test alert',
    description: 'Generated by tests/load/alert-ingestion.js',
    severity: 3, // Low — avoids tripping any real alert-rule side effects
    timestampUtc: new Date().toISOString(),
    environment: 'load-test',
    region: null,
    metadata: null,
  });

  const timestamp = Math.floor(Date.now() / 1000).toString();
  const signature = sign(timestamp, body);

  const response = http.post(`${BASE_URL}/api/v1/integrations/${INTEGRATION_ID}/alerts`, body, {
    headers: {
      'Content-Type': 'application/json',
      'X-Api-Key': API_KEY,
      'X-SentinelOps-Timestamp': timestamp,
      'X-SentinelOps-Signature': signature,
      'Idempotency-Key': `${__VU}-${__ITER}-${Date.now()}`,
    },
  });

  check(response, {
    'status is 202': (r) => r.status === 202,
    'response has alertId': (r) => {
      try {
        return typeof JSON.parse(r.body).alertId === 'string';
      } catch {
        return false;
      }
    },
  });

  sleep(1);
}
